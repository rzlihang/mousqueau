import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const tokens = JSON.parse(read('docs/design-system/tokens.json')).color.tokens;
const palettes = Object.fromEntries(['light', 'dark'].map(mode => [mode, Object.fromEntries(tokens.map(({name, value}) => {
  if (!/^[a-z][a-z0-9-]*$/.test(name)) throw Error(`Invalid token: ${name}`);
  const color = typeof value === 'string' ? value : value[mode];
  if (typeof color !== 'string' || /[;{}<>]/.test(color)) throw Error(`Invalid color: ${name}/${mode}`);
  return [name, color];
}))]));
if (new Set(tokens.map(t => t.name)).size !== tokens.length) throw Error('Duplicate color token');
const outputs = new Map();
const declarations = mode => Object.entries(palettes[mode]).map(([name, value]) => `  --${name}: ${value};`).join('\n');
outputs.set('frontend/src/colors.generated.css', `/* Generated by scripts/colors.mjs; edit docs/design-system/tokens.json. */
:root, [data-theme="light"] {\n${declarations('light')}\n  color-scheme: light;\n}
[data-theme="dark"] {\n${declarations('dark')}\n  color-scheme: dark;\n}
@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));
@theme inline {\n${tokens.map(({name}) => `  --color-${name}: var(--${name});`).join('\n')}\n}
`);
outputs.set('frontend/src/colors.generated.ts', `// Generated by scripts/colors.mjs; do not edit.\nexport const colors = ${JSON.stringify(palettes, null, 2)} as const;\n`);
const rgb = mode => {
  const value = palettes[mode].bg;
  if (!/^#[\da-f]{6}$/i.test(value)) throw Error('Native bg must be #rrggbb');
  return value.slice(1).match(/../g).map(v => `0x${v}`).join(', ');
};
outputs.set('colors_generated.go', `// Code generated by scripts/colors.mjs; DO NOT EDIT.
package main

import "github.com/wailsapp/wails/v3/pkg/application"

func ground(dark bool) application.RGBA {
	if dark {
		return application.NewRGB(${rgb('dark')})
	}
	return application.NewRGB(${rgb('light')})
}
`);
const startup = `<!-- colors:start (generated by scripts/colors.mjs) -->
    <style>
      html { background: ${palettes.light.bg}; color-scheme: light; }
      @media (prefers-color-scheme: dark) { html { background: ${palettes.dark.bg}; color-scheme: dark; } }
      html[data-theme="light"] { background: ${palettes.light.bg}; color-scheme: light; }
      html[data-theme="dark"] { background: ${palettes.dark.bg}; color-scheme: dark; }
    </style>
    <script>
      (function () {
        var params = new URLSearchParams(location.search);
        var choice = params.get("theme");
        if (choice === null) {
          try { choice = localStorage.getItem("mousqueau-theme"); } catch (_) {}
        }
        var dark = choice === "dark" || (choice !== "light" && matchMedia("(prefers-color-scheme: dark)").matches);
        document.documentElement.dataset.theme = dark ? "dark" : "light";
      })();
    </script>
    <!-- colors:end -->`;
const html = read('frontend/index.html');
const block = /<!-- colors:start[\s\S]*?<!-- colors:end -->/;
if (!block.test(html)) throw Error('Missing startup color markers');
outputs.set('frontend/index.html', html.replace(block, startup));
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (read(path) !== content) throw Error(`Stale generated colors: ${path}; run pnpm colors:generate`);
  } else writeFileSync(fileURLToPath(new URL(path, root)), content);
}
